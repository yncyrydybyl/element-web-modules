def tokens(p, sans, mono="'Comic Shanns Mono', 'Cascadia Code', monospace", extra=None, success_text=None, accent_text=None, deco=None):
    t = {
        "--cpd-color-theme-bg": p["bg"],
        "--cpd-color-bg-canvas-default": p["bg"],
        "--cpd-color-bg-subtle-secondary": p["sidebar"],
        "--cpd-color-bg-subtle-primary": p["rail"],
        "--cpd-color-bg-action-primary-rest": p["text"],
        "--cpd-color-bg-accent-rest": p["accent"],
        "--cpd-color-bg-critical-primary": p["critical"],
        "--cpd-color-text-primary": p["text"],
        "--cpd-color-text-secondary": p["muted"],
        "--cpd-color-text-action-accent": accent_text or p["accent"],
        "--cpd-color-text-link-external": accent_text or p["accent"],
        "--cpd-color-text-on-solid-primary": p["onAccent"],
        "--cpd-color-text-critical-primary": p["critical"],
        "--cpd-color-text-success-primary": success_text or p["success"],
        "--cpd-color-icon-primary": p["text"],
        "--cpd-color-icon-secondary": p["muted"],
        "--cpd-color-icon-accent-primary": p["accent"],
        "--cpd-color-border-interactive-primary": p["border"],
        "--cpd-color-border-focused": p["accent"],
        "--cpd-font-family-sans": sans,
        "--cpd-font-family-mono": mono,
    }
    if deco:
        for i, (fg, bg) in enumerate(deco, 1):
            t[f"--cpd-color-text-decorative-{i}"] = fg
            t[f"--cpd-color-bg-decorative-{i}"] = bg
    if extra:
        t.update(extra)
    return t

